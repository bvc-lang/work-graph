function readJson(relativePath) {
  return JSON.parse(readFileSync(join(TOKENS_ROOT, relativePath), 'utf8'));
}

function mergeDeep(target, source) {
  const next = { ...target };
  for (const [key, value] of Object.entries(source ?? {})) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      next[key] = mergeDeep(next[key] ?? {}, value);
    } else {
      next[key] = value;
    }
  }
  return next;
}

/**
 * Resolve theme JSON with optional base.json merge.
 * @param {string} themeFile e.g. themes/marketplace-default.json
 */
export function loadThemeTokens(themeFile) {
  const theme = readJson(themeFile);
  if (theme.extends === 'base') {
    const base = readJson('base.json');
    return mergeDeep(base, theme);
  }
  return theme;
}

function cssVarLines(map, section) {
  const lines = [];
  for (const [jsonKey, cssName] of Object.entries(map)) {
    const value = section?.[jsonKey];
    if (value !== undefined && value !== '') {
      lines.push(`  ${cssName}: ${value};`);
    }
  }
  return lines;
}

/**
 * @param {object} tokens merged theme object
 * @param {{ selector?: string, banner?: string }} [options]
 */
export function tokensToCss(tokens, options = {}) {
  const selector = options.selector ?? ':root';
  const banner = options.banner ?? 'Generated by @iohasc/design-tokens — do not edit by hand.';
  const brandLines = cssVarLines(BRAND_KEYS, tokens.brand);
  const typographyLines = cssVarLines(TYPOGRAPHY_KEYS, tokens.typography);
  const uiLines = cssVarLines(UI_KEYS, tokens.ui);
  const lines = [
    `/**`,
    ` * ${banner}`,
    ` * theme: ${tokens.themeId ?? 'base'}`,
    ` */`,
    `${selector} {`,
    ...brandLines,
    '',
    '  /* Typography (Marketplace scale) */',
    ...typographyLines,
    '  --font-size-sm: var(--text-sm);',
    '  --font-size-base: var(--text-base);',
    '',
    '  /* Runtime UI semantic tokens */',
    ...uiLines,
    '}',
    '',
  ];
  return lines.join('\n');
}

/**
 * @param {string} themeFile
 * @param {{ selector?: string }} [options]
 */
export function themeFileToCss(themeFile, options = {}) {
  const tokens = loadThemeTokens(themeFile);
  return tokensToCss(tokens, options);
}

